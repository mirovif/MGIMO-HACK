import re
import unicodedata


PRIVATE_DATA = re.compile(
    r'\b(?:pza_|sk-(?:proj-)?)[\w-]{16,}\b'
    r'|\b[\w.+-]+@[\w.-]+\.[a-zа-я]{2,}\b'
    r'|(?<!\w)(?:\+7|8)[\s(.-]*\d{3}[\s).-]*\d{3}[\s.-]*\d{2}[\s.-]*\d{2}(?!\d)'
    r'|\b\d{3}-\d{3}-\d{3}\s+\d{2}\b'
    r'|\b\d{2}\s\d{2}\s\d{6}\b'
    r'|\b(?:пароль|токен|api[_ -]?key|снилс|паспорт)\s*[:=]\s*\S+',
    re.IGNORECASE,
)

UNSAFE_REQUEST = re.compile(
    r'\b(?:поддела(?:ть|й|йте)|сфальсифицирова(?:ть|й)|сфальсифициру(?:й|йте)'
    r'|взлома(?:ть|й|йте)|сфабрикова(?:ть|й)|сфабрику(?:й|йте))\b'
    r'|\bкак\b.{0,24}\b(?:списать|списывать)\b.{0,60}\b(?:экзамен|зач[её]т|контрольн)\w*'
    r'|\b(?:обойти|обход)\b.{0,50}\b(?:прокторинг|авторизаци|защит|провер)\w*'
    r'|\b(?:игнорируй|забудь|обойди)\b.{0,60}\b(?:инструкци|ограничени|системн)\w*'
    r'|\b(?:покажи|выведи|раскрой|достань|дай|сообщи|скажи)\b.{0,70}'
    r'(?:системн\w*\s+(?:промпт|инструкци)|api[_ -]?key|ключ\s+api|ключ\s+polza'
    r'|чуж\w*\s+(?:парол|оценк|телефон|данн)|данн\w*\s+друг\w*\s+студент)',
    re.IGNORECASE,
)

REFUSAL = (
    'Я помогаю с официальными правилами и учебными процедурами РЭУ. '
    'Спросите, как решить ситуацию законным способом или куда обратиться.'
)


def safety_reply(question: str) -> str | None:
    normalized = unicodedata.normalize('NFKC', question).replace('\u200b', '')
    normalized = ' '.join(normalized.split())
    if PRIVATE_DATA.search(normalized):
        return 'Уберите из вопроса пароли, токены, личные контакты и номера документов, затем отправьте его снова.'
    if UNSAFE_REQUEST.search(normalized):
        return REFUSAL
    return None
